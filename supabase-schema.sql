create policy "phone_pro_read_warehouses" on warehouses for select using (true);
create policy "phone_pro_read_warehouse_stocks" on warehouse_stocks for select using (true);
create policy "phone_pro_read_invoices" on invoices for select using (true);
create policy "phone_pro_insert_invoices" on invoices for insert with check (true);

