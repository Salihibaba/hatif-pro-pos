create table if not exists products (
  id integer primary key,
  name text not null,
  category text not null,
  price integer not null default 0,
  cost integer not null default 0,
  stock integer not null default 0,
  imei text not null default '-',
  icon text not null default '▰',
  created_at timestamptz not null default now()
);

create table if not exists customers (
  name text primary key,
  type text not null,
  total text not null default '0 أوقية',
  created_at timestamptz not null default now()
);

create table if not exists warehouses (
  code text primary key,
  name text not null,
  branch text not null,
  manager text not null,
  capacity integer not null default 0,
  used integer not null default 0,
  status text not null default 'نشط',
  created_at timestamptz not null default now()
);

create table if not exists warehouse_stocks (
  id bigint generated by default as identity primary key,
  warehouse text not null,
  product text not null,
  category text not null,
  available integer not null default 0,
  reserved integer not null default 0,
  minimum integer not null default 0,
  created_at timestamptz not null default now()
);

create unique index if not exists warehouse_stocks_unique_item
  on warehouse_stocks (warehouse, product);

create table if not exists invoices (
  number text primary key,
  customer text not null,
  issued_at timestamptz not null default now(),
  label_date text,
  total_label text,
  total_amount integer not null default 0,
  status text not null default 'مدفوعة',
  items jsonb not null default '[]'::jsonb
);

alter table products enable row level security;
alter table customers enable row level security;
alter table warehouses enable row level security;
alter table warehouse_stocks enable row level security;
alter table invoices enable row level security;

